# Function 1: Inspect diameter and return bin label

def inspect(dia):
    if 9.8 <= dia <= 10.2:
        return "ACCEPT"
    elif 9.5 <= dia < 9.8 or 10.2 < dia <= 10.5:
        return "REWORK"
    else:
        return "SCRAP"


# Function 2: Tally inspection labels

def tally(labels):
    counts = {
        "ACCEPT": 0,
        "REWORK": 0,
        "SCRAP": 0
    }

    for label in labels:
        counts[label] += 1

    return counts


# Function 3: Generate formatted shift report

def report(shift, counts):
    return (
        f"Shift {shift} | "
        f"ACCEPT: {counts['ACCEPT']} | "
        f"REWORK: {counts['REWORK']} | "
        f"SCRAP: {counts['SCRAP']}"
    )


