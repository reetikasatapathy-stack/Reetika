import random

# Production settings
TARGET_ACCEPTS = 5
MAX_ATTEMPTS = 500

consecutive_accepts = 0
total_attempts = 0

print("===== CONSECUTIVE ACCEPT PRODUCTION =====")

# Continue until five consecutive ACCEPTs or safety cap
while (
    consecutive_accepts < TARGET_ACCEPTS
    and total_attempts < MAX_ATTEMPTS
):
    total_attempts += 1

    diameter = round(random.uniform(24.80, 25.20), 2)

    # Three-bin classification
    if 24.95 <= diameter <= 25.05:
        bin_label = "ACCEPT"
        consecutive_accepts += 1

    elif 24.90 <= diameter <= 25.10:
        bin_label = "REWORK"
        consecutive_accepts = 0

    else:
        bin_label = "SCRAP"
        consecutive_accepts = 0

    print(
        f"Part {total_attempts}: "
        f"{diameter:.2f} mm - {bin_label} | "
        f"Consecutive ACCEPTs: {consecutive_accepts}"
    )

# Final production report
print("\n========== SHIFT REPORT ==========")
print("Total Parts Machined :", total_attempts)
print("Target ACCEPTs       :", TARGET_ACCEPTS)
print("Consecutive ACCEPTs  :", consecutive_accepts)

if consecutive_accepts == TARGET_ACCEPTS:
    print("Result               : TARGET ACHIEVED")
else:
    print("Result               : SAFETY CAP REACHED")

print("==================================")

# Verify safety limit
assert total_attempts <= MAX_ATTEMPTS