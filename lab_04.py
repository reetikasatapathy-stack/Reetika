import random

# Operator selects production mode
mode = input("Select mode (HALT / SKIP): ").strip().upper()

if mode not in ("HALT", "SKIP"):
    print("Invalid mode. Choose HALT or SKIP.")

else:
    accept_count = 0
    rework_count = 0
    scrap_count = 0
    inspected_count = 0

    total_parts = 100

    print(f"\nProduction started in {mode} mode.")

    for i in range(total_parts):

        diameter = round(random.uniform(24.80, 25.20), 2)
        inspected_count += 1

        # Job 09 three-bin classification
        if 24.95 <= diameter <= 25.05:
            bin_label = "ACCEPT"
            accept_count += 1

        elif 24.90 <= diameter <= 25.10:
            bin_label = "REWORK"
            rework_count += 1

        else:
            bin_label = "SCRAP"
            scrap_count += 1

        print(
            f"Part {i + 1}: "
            f"{diameter:.2f} mm - {bin_label}"
        )

        # HALT mode: stop at first SCRAP
        if bin_label == "SCRAP" and mode == "HALT":
            print("\nSCRAP detected! Production halted.")
            break

        # SKIP mode: record scrap and continue
        elif bin_label == "SCRAP" and mode == "SKIP":
            print("SCRAP logged. Continuing production.")
            continue

    # Final shift report
    print("\n========== SHIFT REPORT ==========")
    print("Production Mode :", mode)
    print("Parts Inspected :", inspected_count)
    print("ACCEPT          :", accept_count)
    print("REWORK          :", rework_count)
    print("SCRAP           :", scrap_count)

    if mode == "HALT" and scrap_count > 0:
        print("Status          : STOPPED AT FIRST SCRAP")
    else:
        print("Status          : BATCH COMPLETED")

    print("==================================")

    assert (
        accept_count + rework_count + scrap_count
        == inspected_count
    )

