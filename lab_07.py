import random

# Machine class
class Machine:

    def __init__(self, name, min_limit, max_limit):
        self.name = name
        self.__min_limit = min_limit
        self.__max_limit = max_limit

        self.__accepted = 0
        self.__rejected = 0
        self.__processed = 0

    # Process one job
    def process(self, diameter):

        self.__processed += 1

        if self.__min_limit <= diameter <= self.__max_limit:
            self.__accepted += 1
            print(diameter, "-> ACCEPT")
            return True

        else:
            self.__rejected += 1
            print(diameter, "-> REJECT")
            return False

    # Return machine status
    def status(self):
        return {
            "Machine": self.name,
            "Processed": self.__processed,
            "Accepted": self.__accepted,
            "Rejected": self.__rejected
        }


# Commission machine
machine = Machine("Lathe Machine", 9.8, 10.2)

# Generate ten jobs
print("===== BATCH PROCESSING =====")

for i in range(10):

    diameter = round(random.uniform(9.4, 10.6), 2)

    print("Job", i + 1, end=": ")
    machine.process(diameter)


# Final shift report
print("\n===== SHIFT REPORT =====")

report = machine.status()

for key, value in report.items():
    print(key, ":", value)

# Audit check
print("\n===== AUDIT =====")

print(
    "Processing audit:",
    report["Accepted"] + report["Rejected"]
    == report["Processed"]
)

