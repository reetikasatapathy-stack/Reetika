# Define Machine class

class Machine:

    def __init__(self, name, machine_id, limit):
        self.name = name
        self.machine_id = machine_id
        self.limit = limit
        self.total_parts = 0

    # Nameplate
    def __str__(self):
        return (f"Machine: {self.name} | "
                f"ID: {self.machine_id} | "
                f"Limit: {self.limit} | "
                f"Total Parts: {self.total_parts}")

    # Working method
    def produce(self, parts):
        self.total_parts += parts

        if self.total_parts <= self.limit:
            return "Machine operating normally"
        else:
            return "Limit exceeded"


