class Machine:

    def __init__(self, name, min_limit, max_limit):
        self.name = name
        self.__min_limit = min_limit
        self.__max_limit = max_limit
        self.__parts = 0
        self.__busy = False

    def process(self, diameter):

        if self.__min_limit <= diameter <= self.__max_limit:
            self.__parts += 1
            self.__busy = False
            return "ACCEPT"

        else:
            self.__busy = False
            return "REJECT"

    def is_free(self):
        return not self.__busy

    def start_job(self):
        self.__busy = True

    def status(self):
        return {
            "name": self.name,
            "parts": self.__parts,
            "busy": self.__busy
        }

    def parts_count(self):
        return self.__parts