class Machine:

    def __init__(self, name, min_limit, max_limit):
        self.name = name
        self.__min_limit = min_limit
        self.__max_limit = max_limit
        self.__speed = 0

    # Validating operating method
    def operate(self, speed):

        if speed < self.__min_limit or speed > self.__max_limit:
            print("ERROR: Speed out of allowed range!")
            print("Command rejected.")
            return False

        self.__speed = speed
        print("Machine operating successfully.")
        return True

    # Status getter
    def status(self):
        return {
            "Machine": self.name,
            "Current Speed": self.__speed,
            "Minimum Speed": self.__min_limit,
            "Maximum Speed": self.__max_limit
        }


