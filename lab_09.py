import os
import re
import csv
from datetime import datetime

DATA_DIR = "data"
REPORT_DIR = os.path.join(DATA_DIR, "reports")
HISTORY_FILE = os.path.join(DATA_DIR, "run_history.csv")

os.makedirs(REPORT_DIR, exist_ok=True)

# Three-field record: part code, diameter, shift
pattern = re.compile(
    r"^\s*(P\d{3})\s*,\s*"
    r"(\d+(?:\.\d+)?)\s*,\s*"
    r"(S\d)\s*$"
)

# Plant-wide counters
plant_counts = {
    "ACCEPT": 0,
    "REWORK": 0,
    "SCRAP": 0
}

plant_processed = 0
plant_rejected = 0

# One timestamp for this complete run
timestamp = datetime.now().isoformat(timespec="seconds")

# Find every input TXT file directly inside data/
input_files = sorted(
    filename
    for filename in os.listdir(DATA_DIR)
    if filename.lower().endswith(".txt")
    and os.path.isfile(os.path.join(DATA_DIR, filename))
    and filename != "plant_summary.txt"
    and not filename.startswith("report_")
)

history_rows = []

# Process each file
for filename in input_files:

    filepath = os.path.join(DATA_DIR, filename)

    counts = {
        "ACCEPT": 0,
        "REWORK": 0,
        "SCRAP": 0
    }

    rejects = []
    processed = 0

    # READ
    with open(filepath, "r") as file:
        lines = file.readlines()

    # PARSE AND VALIDATE
    for line_number, line in enumerate(lines, start=1):

        raw = line.strip()
        match = pattern.fullmatch(raw)

        if not match:
            rejects.append((line_number, raw, "Invalid format"))
            continue

        code, diameter_text, shift = match.groups()

        try:
            diameter = float(diameter_text)
        except ValueError:
            rejects.append((line_number, raw, "Invalid diameter"))
            continue

        if diameter <= 0:
            rejects.append((line_number, raw, "Non-positive diameter"))
            continue

        # CLASSIFY
        if 9.8 <= diameter <= 10.2:
            label = "ACCEPT"
        elif 9.5 <= diameter <= 10.5:
            label = "REWORK"
        else:
            label = "SCRAP"

        # AGGREGATE
        counts[label] += 1
        processed += 1

    rejected = len(rejects)

    # Update plant totals
    for label in plant_counts:
        plant_counts[label] += counts[label]

    plant_processed += processed
    plant_rejected += rejected

    # WRITE INDIVIDUAL REPORT
    report_name = "report_" + filename.replace(".txt", "") + ".txt"
    report_path = os.path.join(REPORT_DIR, report_name)

    with open(report_path, "w") as report:

        report.write("========== FILE SHIFT REPORT ==========\n")
        report.write(f"File: {filename}\n")
        report.write(f"{'BIN':<15}{'COUNT':>10}\n")
        report.write("-" * 25 + "\n")

        for label, count in counts.items():
            report.write(f"{label:<15}{count:>10}\n")

        report.write("-" * 25 + "\n")
        report.write(f"Records processed: {processed}\n")
        report.write(f"Rejected records: {rejected}\n")

        report.write(
            "Audit: " +
            str(sum(counts.values()) == processed) + "\n"
        )

    # Prepare history entry
    history_rows.append([
        timestamp,
        filename,
        processed,
        rejected
    ])

    print("Processed:", filename)


# WRITE COMBINED PLANT SUMMARY
with open(os.path.join(DATA_DIR, "plant_summary.txt"), "w") as report:

    report.write("========== PLANT SUMMARY ==========\n\n")

    report.write(f"{'BIN':<15}{'COUNT':>10}\n")
    report.write("-" * 25 + "\n")

    for label, count in plant_counts.items():
        report.write(f"{label:<15}{count:>10}\n")

    report.write("-" * 25 + "\n")
    report.write(f"Total processed: {plant_processed}\n")
    report.write(f"Total rejected: {plant_rejected}\n")

    report.write(
        "Plant audit: " +
        str(sum(plant_counts.values()) == plant_processed)
        + "\n"
    )


# APPEND RUN HISTORY
history_exists = (
    os.path.exists(HISTORY_FILE)
    and os.path.getsize(HISTORY_FILE) > 0
)

with open(HISTORY_FILE, "a", newline="") as file:

    writer = csv.writer(file)

    if not history_exists:
        writer.writerow([
            "timestamp",
            "file_name",
            "records_processed",
            "rejects"
        ])

    writer.writerows(history_rows)


# FINAL CONSOLE SUMMARY
print("\n========== PLANT RUN COMPLETE ==========")
print("Files processed:", len(input_files))
print("Total records:", plant_processed)
print("Total rejects:", plant_rejected)
print("ACCEPT:", plant_counts["ACCEPT"])
print("REWORK:", plant_counts["REWORK"])
print("SCRAP:", plant_counts["SCRAP"])
print("Plant audit:",
      sum(plant_counts.values()) == plant_processed)

print("\nReports saved:", REPORT_DIR)
print("Plant summary: data/plant_summary.txt")
print("History: data/run_history.csv")