# Job 15: Compare Day and Night shift scrap lists

day_logs = [
    "P101 , 25.06 , Day",
    "P102, 24.98, Day",
    "P103 , 25.12 , Day",
    "P104, 25.03, Day",
    "P105 , 24.91 , Day"
]

night_logs = [
    "P103 , 25.11 , Night",
    "P106, 25.02, Night",
    "P107 , 24.97 , Night",
    "P108, 25.09, Night",
    "P109 , 25.05, Night"
]

# Function to parse a shift
def process_shift(logs):
    accepted = []
    scrap = []

    for log in logs:
        part_code, diameter, shift = log.split(",")
        part_code = part_code.strip()
        dia = float(diameter.strip())

        # Accepted range
        if 25.00 <= dia <= 25.08:
            accepted.append(part_code)
        else:
            scrap.append(part_code)

    return accepted, scrap


# Parse Day and Night separately
day_accepted, day_scrap = process_shift(day_logs)
night_accepted, night_scrap = process_shift(night_logs)


# Calculate accept rates
day_rate = (len(day_accepted) / len(day_logs)) * 100
night_rate = (len(night_accepted) / len(night_logs)) * 100


# Convert scrap lists to sets
day_scrap_set = set(day_scrap)
night_scrap_set = set(night_scrap)

# Part codes scrapped in BOTH shifts
both_scrap = day_scrap_set & night_scrap_set

# Part codes unique to Day
day_only = day_scrap_set - night_scrap_set

# Part codes unique to Night
night_only = night_scrap_set - day_scrap_set


# Report
print("DAY SHIFT")
print("Accepted:", day_accepted)
print("Scrap:", day_scrap)
print("Accept Rate:", day_rate, "%")

print("\nNIGHT SHIFT")
print("Accepted:", night_accepted)
print("Scrap:", night_scrap)
print("Accept Rate:", night_rate, "%")

print("\nCOMPARISON")
print("Scrapped in BOTH shifts:", both_scrap)
print("Scrapped only in DAY:", day_only)
print("Scrapped only in NIGHT:", night_only)