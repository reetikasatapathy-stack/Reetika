from pathlib import Path
import logging

# Use Path.cwd() instead of __file__ in Jupyter/Colab notebooks
BASE_DIR = Path.cwd()
DATA_DIR = BASE_DIR / "data"
REPORTS_DIR = BASE_DIR / "reports"

INPUT_FILE = DATA_DIR / "sample.txt"
OUTPUT_FILE = REPORTS_DIR / "output.txt"

logging.basicConfig(
    level=logging.INFO,
    format="%(levelname)s: %(message)s"
)

logger = logging.getLogger(__name__)


def process_text(content: str) -> str:
    """Validate and process input text."""
    if not isinstance(content, str):
        raise TypeError("Input must be text.")

    if not content.strip():
        raise ValueError("Input cannot be empty.")

    return content.strip()


def process_file() -> bool:
    """Read sample input and generate a report."""
    try:
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)

        content = INPUT_FILE.read_text(encoding="utf-8")
        result = process_text(content)

        OUTPUT_FILE.write_text(result + "\n", encoding="utf-8")

        logger.info("Processing completed successfully.")
        logger.info("Report saved to %s", OUTPUT_FILE)
        return True

    except FileNotFoundError:
        logger.error("Input file was not found.")
    except PermissionError:
        logger.error("Permission denied while accessing a file.")
    except UnicodeDecodeError:
        logger.error("Input file is not valid UTF-8.")
    except OSError:
        logger.exception("A file operation failed.")

    return False


def run_tests() -> bool:
    """Run normal and hostile-input checks."""
    test_cases = [
        ("Hello World", True),
        ("  Sample text  ", True),
        ("", False),
        ("   ", False),
        (None, False),
        (123, False),
    ]

    for test_input, should_pass in test_cases:
        try:
            process_text(test_input)
            actual = True
        except (TypeError, ValueError):
            actual = False

        assert actual == should_pass, (
            f"Test failed for input: {test_input!r}"
        )

    print("All tests passed.")
    return True


if __name__ == "__main__":
    run_tests()
    process_file()

